import Foundation

/// Persisted independently of system language; changing it updates all observing views.
nonisolated enum AppLanguage: String, CaseIterable, Identifiable {
    case simplifiedChinese = "zh-Hans"
    case english = "en"
    var id: String { rawValue }
    var title: String { self == .simplifiedChinese ? "简体中文" : "English" }
    static var initial: AppLanguage {
        if let stored = UserDefaults.standard.string(forKey: "Glance.language"), let value = Self(rawValue: stored) { return value }
        return Locale.preferredLanguages.first?.hasPrefix("zh") == true ? .simplifiedChinese : .english
    }
}

nonisolated enum L10n {
    @MainActor static func ui(_ text: String) -> String {
        string(text, language: GlanceSettings.shared.language)
    }

    static func string(_ text: String, language: AppLanguage) -> String {
        guard language == .simplifiedChinese else { return text }
        if let translated = chinese[text] { return translated }
        if text.hasPrefix("Almost done — ") {
            let instruction = String(text.dropFirst("Almost done — ".count))
            let key = instruction.prefix(1).uppercased() + instruction.dropFirst()
            return "即将完成，" + (chinese[key] ?? instruction)
        }
        if text.hasPrefix("Capture quality • ") { return text.replacingOccurrences(of: "Capture quality • ", with: "采集质量 · ") }
        if text.hasPrefix("Parameters · ") { return text.replacingOccurrences(of: "Parameters · ", with: "参数 · ") }
        if text.hasSuffix(" days") || text == "1 day" { return text.components(separatedBy: " ")[0] + " 天" }
        if text.hasSuffix(" (Default)") { return text.replacingOccurrences(of: " (Default)", with: "（默认）") }
        if text.hasSuffix(" (disconnected)") { return text.replacingOccurrences(of: " (disconnected)", with: "（未连接）") }
        return text
    }

